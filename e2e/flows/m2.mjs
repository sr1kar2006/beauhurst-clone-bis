// node e2e/flows/m2.mjs : M2 international screenshots
import { chromium } from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('e2e-shots/part3', { recursive: true });
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1844, height: 1032 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && !/openstreetmap|Failed to load/.test(m.text()) && errors.push(m.text()));
await page.addInitScript(() => { try { localStorage.setItem('nb.tourSeen', 'true'); } catch {} });
const t0 = Date.now();
await page.goto('http://localhost:5173/');
await page.locator('[data-tour="country-scope"]').waitFor();
console.log('first load + dataset ms', Date.now() - t0, await page.evaluate(() => performance.getEntriesByName('dataset:ready').map((e) => e.detail)));
await page.locator('[data-tour="country-scope"]').click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'e2e-shots/part3/M2-country-dropdown.png' });
await page.locator('[data-country="ALL"]').click();
await page.keyboard.press('Escape');
await page.getByRole('button', { name: /^view all .* companies in All countries/ }).click();
await page.locator('[data-company-link]').first().waitFor();
await page.evaluate(() => window.scrollTo(0, 450));
await page.waitForTimeout(300);
await page.screenshot({ path: 'e2e-shots/part3/M2-results-intl.png' });
await page.getByRole('tab', { name: /Statistics/ }).click();
await page.locator('[data-tour="stats-by-country"]').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
await page.screenshot({ path: 'e2e-shots/part3/M2-stats-by-country.png' });
await page.getByRole('tab', { name: /Map/ }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: 'e2e-shots/part3/M2-map-ukie.png' });
await page.locator('[data-map-view="all"]').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: 'e2e-shots/part3/M2-map-world.png' });
for (const id of ['de-1', 'us-1', 'jp-1']) {
  await page.goto(`http://localhost:5173/companies/${id}/details`);
  await page.locator('[data-section]').waitFor();
  await page.waitForTimeout(500);
  await page.screenshot({ path: `e2e-shots/part3/M2-profile-${id}-details.png` });
}
await page.goto('http://localhost:5173/companies/de-1/financials');
await page.locator('[data-section]').waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: 'e2e-shots/part3/M2-profile-de-1-financials.png' });
await page.goto('http://localhost:5173/companies/fr-1/filing-history');
await page.locator('[data-section]').waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: 'e2e-shots/part3/M2-profile-fr-1-filings.png' });
console.log(errors.length ? errors.join('\n') : 'no console errors');
await b.close();
